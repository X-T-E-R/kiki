import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createServer as createHttpServer } from 'node:http';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { FIXTURE_TOKEN, startFixtureServer } from './fixture-server.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, '.tmp/sidebar-child-activity');
await mkdir(out, { recursive: true });
const fixture = await startFixtureServer({ port: 0, scenario: 'sidebar-child-activity' });
const fixtureUrl = `http://127.0.0.1:${fixture.http.address().port}`;
process.env.KIKI_SERVER_URL = fixtureUrl;
const vite = await createServer({ root, cacheDir: join(out, 'vite-cache'), optimizeDeps: { entries: ['index.html'] },
  server: { middlewareMode: true, hmr: false, watch: { ignored: ['**/src-tauri/**', '**/.tmp/**'] } }, logLevel: 'error' });
const http = createHttpServer(vite.middlewares);
await new Promise((resolve) => http.listen(0, '127.0.0.1', resolve));
const web = `http://127.0.0.1:${http.address().port}`;
const browser = await chromium.launch({ args: ['--no-proxy-server'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const errors = [];
const parent = 'session_activity_parent';
const child = 'session_activity_child';
const other = 'session_activity_other';
const pinned = 'session_activity_pinned';
const older = 'session_activity_older';
const expectedBefore = [pinned, other, parent, child, older];
const expectedAfter = [pinned, parent, child, other, older];
const report = {};
try {
  await context.addInitScript(() => {
    localStorage.setItem('kiki.locale', 'zh');
    localStorage.setItem('kiki.onboarding', JSON.stringify({ completedAt: '2026-01-01T00:00:00Z' }));
    localStorage.setItem('kiki.layout', JSON.stringify({ groupBy: 'none', sortBy: 'updated-desc', sidebarCollapsed: false }));
  });
  const page = await context.newPage();
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(`${web}/s/${parent}?server=${encodeURIComponent(fixtureUrl)}&token=${FIXTURE_TOKEN}`);
  const sidebar = page.locator('[data-session-sidebar]');
  const ids = () => sidebar.locator('[data-session-row]').evaluateAll((nodes) => nodes.map((node) => node.dataset.sessionRow));
  await page.waitForFunction(() => document.querySelectorAll('[data-session-row]').length === 5);
  report.before = await ids();
  assert.deepEqual(report.before, expectedBefore);
  await sidebar.screenshot({ path: join(out, 'before.png') });
  await sidebar.locator(`[data-session-row="${parent}"] > button`).click({ modifiers: ['Control'] });
  assert.equal(await sidebar.locator(`[data-session-row="${parent}"]`).getAttribute('data-session-selected'), 'true');
  const at = new Date(Date.now() - 60_000).toISOString();
  fixture.sessions.get(child).record.updated_at = at;
  fixture.sessions.get(parent).record.updated_at = at;
  for (const sessionId of [child, parent]) fixture.emit(sessionId, { type: 'session.meta.updated', payload: { sessionId, agentId: 'main', patch: {} } });
  await page.waitForFunction(({ expected }) => JSON.stringify([...document.querySelectorAll('[data-session-sidebar] [data-session-row]')].map((node) => node.dataset.sessionRow)) === JSON.stringify(expected), { expected: expectedAfter });
  report.after = await ids();
  assert.equal(await sidebar.locator(`[data-session-row="${parent}"]`).getAttribute('data-session-selected'), 'true');
  assert.equal(await sidebar.locator(`[data-session-row="${parent}"] > button`).getAttribute('aria-current'), 'page');
  await page.mouse.move(600, 100);
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); });
  assert.match(await sidebar.locator(`[data-session-row="${parent}"] [data-session-time]`).innerText(), /1.*分钟前/);
  await sidebar.screenshot({ path: join(out, 'after.png') });
  await page.reload();
  await page.waitForFunction(({ expected }) => JSON.stringify([...document.querySelectorAll('[data-session-sidebar] [data-session-row]')].map((node) => node.dataset.sessionRow)) === JSON.stringify(expected), { expected: expectedAfter });
  report.reload = await ids();
  assert.equal(await sidebar.locator(`[data-session-row="${parent}"] > button`).getAttribute('aria-current'), 'page');
  const subscribed = fixture.wsInbound.filter((frame) => frame.type === 'subscribe').length;
  await fetch(`${fixtureUrl}/__control`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action: 'drop_ws' }) });
  await page.waitForFunction(async ({ fixtureUrl, subscribed }) => {
    const response = await fetch(`${fixtureUrl}/__control`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action: 'ws_log' }) });
    const body = await response.json();
    return body.data.inbound.filter((frame) => frame.type === 'subscribe').length > subscribed;
  }, { fixtureUrl, subscribed });
  report.reconnect = await ids();
  assert.deepEqual(report.reconnect, expectedAfter);
  for (const id of [parent, other]) await sidebar.locator(`[data-session-row="${id}"] > button`).click({ modifiers: ['Control'] });
  await sidebar.locator(`[data-session-row="${parent}"]`).click({ button: 'right' });
  const menu = page.locator('[data-session-menu]');
  assert.equal(await menu.locator('[data-menu-item="new-thread-room"]').count(), 0);
  assert.equal(await menu.locator('[data-menu-item="open-default-app"]').count(), 0);
  assert.equal(await menu.locator('[data-menu-item="copy-link"]').innerText(), '复制线程链接');
  assert.equal(await menu.locator('[data-menu-item="copy-path"]').innerText(), '复制工作目录');
  await menu.screenshot({ path: join(out, 'menu.png') });
  await menu.locator('[data-menu-item="join-room"]').click();
  await page.locator('[data-join-room-new]').waitFor();
  await page.locator('[role="dialog"]').screenshot({ path: join(out, 'room-choice.png') });
  await page.locator('[data-join-room-new]').click();
  await page.locator('[data-new-thread-room]').waitFor();
  assert.equal(await page.locator('[data-new-thread-room-member]').count(), 2);
  await page.locator('[data-new-thread-room-submit]').click();
  await page.waitForURL(/\/rooms\//);
  const created = [...fixture.rooms.values()].find((entry) => entry.room.members.some((member) => member.sessionId === parent));
  assert.ok(created);
  assert.deepEqual(created.room.members.map((member) => member.sessionId), [parent, other]);
  await sidebar.locator(`[data-session-row="${older}"]`).click({ button: 'right' });
  await page.locator('[data-menu-item="join-room"]').click();
  await page.locator(`[data-join-room="${created.room.id}"]`).click();
  await page.locator('[data-join-room-dialog]').waitFor({ state: 'detached' });
  assert.ok(created.room.members.some((member) => member.sessionId === older));
  report.menu = 'one room entry → empty chooser → create two-thread room → join existing room';
  assert.deepEqual(errors, []);
  await writeFile(join(out, 'receipt.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ out, ...report }, null, 2));
} finally {
  await context.close();
  await browser.close();
  await vite.close();
  await new Promise((resolve) => http.close(resolve));
  await fixture.stop();
}
